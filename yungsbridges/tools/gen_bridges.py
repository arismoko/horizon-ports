"""Writes src/bridges.rs and the data files from YUNG's Bridges' own data folder.

usage: python3 tools/gen_bridges.py <YUNGs-Bridges>/Common/src/main/resources/data/yungsbridges

src/bridges.rs holds bridge_list's 22 entries (BridgePlacement's numbers, the axis, the rarity)
and the templates decoded from their structure files: the palette as placed unrotated and as
placed rotated counterclockwise (StructurePlaceSettings.setRotation(COUNTERCLOCKWISE_90)), and
the blocks in the order StructureTemplate keeps them (by y, then x, then z).
"""
import gzip, json, os, shutil, struct, sys

SRC = sys.argv[1]
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def nbt(path):
    b = gzip.open(path).read()

    def payload(i, t):
        if t == 1: return struct.unpack_from('>b', b, i)[0], i + 1
        if t == 2: return struct.unpack_from('>h', b, i)[0], i + 2
        if t == 3: return struct.unpack_from('>i', b, i)[0], i + 4
        if t == 4: return struct.unpack_from('>q', b, i)[0], i + 8
        if t == 5: return struct.unpack_from('>f', b, i)[0], i + 4
        if t == 6: return struct.unpack_from('>d', b, i)[0], i + 8
        if t in (7, 11, 12):
            n = struct.unpack_from('>i', b, i)[0]; i += 4
            w, f = {7: (1, 'b'), 11: (4, 'i'), 12: (8, 'q')}[t]
            return list(struct.unpack_from('>%d%s' % (n, f), b, i)), i + n * w
        if t == 8:
            n = struct.unpack_from('>H', b, i)[0]; i += 2
            return b[i:i + n].decode(), i + n
        if t == 9:
            et = b[i]; n = struct.unpack_from('>i', b, i + 1)[0]; i += 5
            out = []
            for _ in range(n):
                v, i = payload(i, et); out.append(v)
            return out, i
        if t == 10:
            out = {}
            while True:
                et = b[i]; i += 1
                if et == 0: return out, i
                n = struct.unpack_from('>H', b, i)[0]; i += 2
                k = b[i:i + n].decode(); i += n
                out[k], i = payload(i, et)
        raise ValueError(t)
    n = struct.unpack_from('>H', b, 1)[0]
    return payload(3 + n, 10)[0]


# BlockState.rotate(COUNTERCLOCKWISE_90): north -> west -> south -> east -> north.
CCW = {'north': 'west', 'west': 'south', 'south': 'east', 'east': 'north'}


def rotate(props):
    out = {}
    for k, v in props.items():
        if k == 'facing' and v in CCW:
            out[k] = CCW[v]
        elif k == 'axis' and v in ('x', 'z'):
            out[k] = 'z' if v == 'x' else 'x'
        elif k in CCW:
            out[CCW[k]] = v
        else:
            out[k] = v
    return dict(sorted(out.items()))


# Blocks renamed since the structure files were saved, as the game's data fixer renames them
# when it loads an old structure: 1.21.9 made the chain `iron_chain`.
RENAMES = {'minecraft:chain': 'minecraft:iron_chain'}


def state(name, props):
    name = RENAMES.get(name, name)
    inner = ', '.join(f'("{k}", "{v}")' for k, v in sorted(props.items()))
    return f'("{name}", &[{inner}])'


def main():
    config = json.load(open(os.path.join(SRC, 'worldgen/configured_feature/bridge_list.json')))
    templates, bridges = [], []
    for entry in config['config']['features']:
        cf = json.load(open(os.path.join(SRC, 'worldgen/configured_feature', entry['feature'].split(':')[1] + '.json')))
        location = cf['config']['location']
        if location not in templates:
            templates.append(location)
        place, rarity = entry['placement'][0], entry['placement'][1]
        assert place['type'] == 'yungsbridges:bridge' and rarity['type'] == 'minecraft:rarity_filter'
        assert cf['config'].get('is_z_axis', True) == place.get('is_z_axis', True)
        bridges.append((templates.index(location), place['length'], place['width'], place['min_water_z'], place['max_water_z'],
                        place['width_offset'], place['num_solid_blocks_needed'], str(place.get('is_z_axis', True)).lower(), rarity['chance']))

    out = ['// @generated by tools/gen_bridges.py from YUNG\'s Bridges\' data. Do not edit.',
           '//! The bridges: bridge_list\'s entries and the templates they place.',
           'use super::{Bridge, Template};', '',
           'pub(crate) const BRIDGES: &[Bridge] = &[']
    for t, l, w, lo, hi, wo, n, z, r in bridges:
        out.append(f'    Bridge {{ template: {t}, length: {l}, width: {w}, min_water: {lo}, max_water: {hi}, width_offset: {wo}, solid_needed: {n}, z_axis: {z}, rarity: {r} }},')
    out += ['];', '', 'pub(crate) const TEMPLATES: &[Template] = &[']
    for location in templates:
        s = nbt(os.path.join(SRC, 'structure', location.split(':')[1] + '.nbt'))
        palette = s['palette']
        assert not s.get('entities') and all('nbt' not in b for b in s['blocks']), location
        blocks = sorted(s['blocks'], key=lambda b: (b['pos'][1], b['pos'][0], b['pos'][2]))
        out.append(f'    Template {{\n        id: "{location}",\n        size: {s["size"]},')
        out.append('        palette: &[' + ', '.join(state(p['Name'], p.get('Properties', {})) for p in palette) + '],')
        out.append('        rotated: &[' + ', '.join(state(p['Name'], rotate(p.get('Properties', {}))) for p in palette) + '],')
        out.append('        blocks: &[' + ', '.join(f'([{x}, {y}, {z}], {b["state"]})' for b in blocks for x, y, z in [b['pos']]) + '],')
        out.append('    },')
    out.append('];')
    open(os.path.join(HERE, 'src/bridges.rs'), 'w').write('\n'.join(out) + '\n')

    data = os.path.join(HERE, 'data/yungsbridges')
    shutil.rmtree(data, ignore_errors=True)
    for sub in ('tags/worldgen/biome', 'neoforge/biome_modifier', 'worldgen/placed_feature'):
        shutil.copytree(os.path.join(SRC, sub), os.path.join(data, sub))
    os.makedirs(os.path.join(data, 'worldgen/feature'))
    with open(os.path.join(data, 'worldgen/feature/bridge_list.json'), 'w') as f:
        f.write('{\n  "type": "yungsbridges:bridge_list"\n}\n')


if __name__ == '__main__':
    main()
